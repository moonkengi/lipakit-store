#!/usr/bin/env node
/**
 * Builds supabase/setup.sql: every migration in order, then the seed, in one
 * file you can paste into the Supabase SQL editor. Regenerate after adding a
 * migration: pnpm db:bundle  (a test fails if the bundle is out of date).
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export function buildBundle(root = process.cwd()) {
  const dir = join(root, "supabase", "migrations");
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort();
  const parts = files.map((f) => `-- >>> supabase/migrations/${f}\n${readFileSync(join(dir, f), "utf8").trim()}\n`);
  parts.push(`-- >>> supabase/seed.sql\n${readFileSync(join(root, "supabase", "seed.sql"), "utf8").trim()}\n`);
  return [
    "-- =============================================================================",
    "-- LipaKit: complete database setup in one file.",
    "-- Paste into Supabase → SQL Editor → Run, on a NEW project. Generated by",
    "-- `pnpm db:bundle` from supabase/migrations/*.sql and supabase/seed.sql; don't edit by hand.",
    "-- (With the Supabase CLI, use `supabase db push` instead, which runs the same files.)",
    "-- =============================================================================",
    "",
    parts.join("\n"),
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(process.cwd(), "supabase", "setup.sql"), buildBundle());
  console.log("Wrote supabase/setup.sql");
}
